    msg += `👤 *Customer Name:* ${name}\n`;
    msg += `📞 *Phone Number:* ${phone}\n`;
    if (email) {
        msg += `📧 *Email Address:* ${email}\n`;
    }
    msg += `🚗 *Trip Type:* ${type}\n`;
    msg += `📍 *Pickup Address in Patna:* ${pickup}\n`;
    msg += `📝 *Trip Details / Notes:* ${details}\n\n`;
    msg += `_Sent via Patna Transport Website Booking (8877177161)_`;

